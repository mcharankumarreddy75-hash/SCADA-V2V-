#!/usr/bin/env python3
"""Analyse V2V field-test data and write PNG plots plus docs/results/summary.md.

Inputs (each optional, give at least one):
  --db PATH              SCADA historian (scada/historian/v2v.db, schema scada/historian/schema.sql)
                         -> PDR vs distance, RSSI vs distance, TTC at warning moments, alarm counts
  --rtt PATH             A3 latency input. Either CSV with header "ts,rtt_ms" (one PING per row),
                         or any text with modbus_probe lines (LAST_RTT_MS)=N or rtt=Nms
                         -> one-way latency (RTT/2) histogram, mean and max vs A3 targets
  --distance-error PATH  A5 tape CSV with header "tape_m,gps_m" (gps_m = average of the GPS distance)
                         -> error table and bar chart, criterion |error| <= 5 m
  --imu-log PATH         LOG_MODE CSV from tools/serial_log.py (header "ms,a_long_x100,...").
                         Lines may carry a serial_log "HH:MM:SS.mmm " prefix; other lines are skipped.
                         -> time series with the current thresholds from config.h, 60 % lines,
                            max |value| per channel and the S13.3 verdict, TTC at warning transitions

Examples (repo root):
  tools/.venv/Scripts/python.exe tools/log_analyzer.py --db scada/historian/v2v.db
  tools/.venv/Scripts/python.exe tools/log_analyzer.py --imu-log data/normal_drive_1.csv
  tools/.venv/Scripts/python.exe tools/log_analyzer.py --db data/sample/sample_v2v.db --out-dir docs/results/sample

Options:
  --out-dir DIR    where PNGs and summary.md go (default docs/results)
  --from / --to    time window for --db: epoch ms, or local time "YYYY-MM-DDTHH:MM:SS"
  --bin-m N        distance bin width in metres for PDR / RSSI (default 25)
  --synthetic      force the SYNTHETIC banner. It is also automatic when an input file name starts
                   with "sample_".

summary.md: each analysis writes one section delimited by <!-- section:ID --> markers. A later run
replaces only its own sections, so analysing one input at a time keeps the others. The "inputs"
section lists what the latest run was given and which inputs were missing. A run never mixes
synthetic and real sections: if the existing summary's synthetic state differs, it is rebuilt.
"""
import argparse
import csv
import datetime as dt
import re
import sqlite3
import sys
from collections import Counter, OrderedDict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
CONFIG_H = ROOT / "firmware" / "v2v_obu" / "config.h"
DEFAULT_OUT = ROOT / "docs" / "results"

# Categorical slots 1-3 of the dataviz reference palette (light surface). Checked with
# validate_palette.js --pairs all: CVD and normal-vision gates pass; contrast WARN, so every
# chart has a legend or direct labels.
BLUE, ORANGE, AQUA = "#257de0", "#f47230", "#00b894"
GRAY = "#666666"
RED = "#dc3c3d"   # status "critical" step, used only for limits and targets

SYN_BANNER = (
    "> **SYNTHETIC - NOT REAL MEASUREMENTS.** These results were generated by "
    "`tools/make_sample_data.py` to test the analyzer. Do not quote them in the report."
)
SECTION_RE = re.compile(r"<!-- section:(\S+) -->\n(.*?)\n<!-- /section:\1 -->", re.S)
DEFINE_RE = re.compile(r"^\s*#define\s+([A-Z][A-Z0-9_]*)\s+(-?\d+(?:\.\d+)?)\b", re.M)
TS_PREFIX_RE = re.compile(r"^\d{2}:\d{2}:\d{2}\.\d{3}\s+")
PROBE_RES = [re.compile(r"LAST_RTT_MS\)=(\d+)"), re.compile(r"\brtt=(\d+)ms")]

# Set in main(): "[SYNTHETIC] " for sample runs, so every PNG title says so.
TITLE_PREFIX = ""


# ---------------------------------------------------------------- helpers

def read_defines(path=CONFIG_H):
    """Numeric #define values from config.h (no hard-coded thresholds in this tool)."""
    text = Path(path).read_text(encoding="utf-8")
    return {m.group(1): float(m.group(2)) for m in DEFINE_RE.finditer(text)}


def thresholds():
    """Current firmware thresholds, in the units of the LOG_MODE CSV columns."""
    d = read_defines()
    g = d["GRAVITY_MS2"]
    return OrderedDict([
        ("a_long", abs(d["HARD_BRAKE_MS2"])),   # m/s^2 (EEBL, braking)
        ("a_total", d["CRASH_G"]),              # g (crash)
        ("az_hp", d["POTHOLE_G"] * g),          # m/s^2 (pothole; POTHOLE_G is in g)
        ("roll", d["ROLLOVER_DEG"]),            # deg (rollover; pitch uses the same limit)
    ])


def parse_time(text):
    """Epoch ms from an int or a local 'YYYY-MM-DDTHH:MM:SS' string. None if not given."""
    if text is None:
        return None
    try:
        return int(text)
    except ValueError:
        return int(dt.datetime.fromisoformat(text).timestamp() * 1000)


def local_time(ts_ms):
    return dt.datetime.fromtimestamp(ts_ms / 1000.0).strftime("%Y-%m-%d %H:%M:%S")


def md_table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def bin_stats(xs, ys, width):
    """(lo, hi, n, mean, min, max) per distance bin."""
    bins = {}
    for x, y in zip(xs, ys):
        bins.setdefault(int(x // width), []).append(y)
    out = []
    for k in sorted(bins):
        v = bins[k]
        out.append((k * width, (k + 1) * width, len(v), sum(v) / len(v), min(v), max(v)))
    return out


def new_fig(nrows=1, ncols=1, w=7.5, h=4.2):
    fig, axes = plt.subplots(nrows, ncols, figsize=(w, h))
    for ax in (axes.flat if hasattr(axes, "flat") else [axes]):
        ax.spines["top"].set_visible(False)
        ax.spines["right"].set_visible(False)
        ax.grid(True, color="#cccccc", alpha=0.5, linewidth=0.6)
        ax.set_axisbelow(True)
    return fig, axes


def save(fig, out_dir, name):
    fig.tight_layout()
    fig.savefig(out_dir / name, dpi=120)
    plt.close(fig)
    return name


def ptitle(text):
    return TITLE_PREFIX + text


def img(name, alt):
    return f"![{alt}]({name})"


# ---------------------------------------------------------------- --db (SCADA historian)

def analyze_db(ctx):
    path = Path(ctx.path).resolve()
    conn = sqlite3.connect(path.as_uri() + "?mode=ro", uri=True)
    try:
        where, args = "", []
        if ctx.t0 is not None:
            where += " AND ts >= ?"
            args.append(ctx.t0)
        if ctx.t1 is not None:
            where += " AND ts <= ?"
            args.append(ctx.t1)
        tel = conn.execute(
            "SELECT ts, vehicle_id, distance, rssi, pdr, ttc, warn FROM telemetry "
            "WHERE 1=1" + where + " ORDER BY vehicle_id, ts", args).fetchall()
        alm = conn.execute(
            "SELECT ts, vehicle_id, type, severity FROM alarms WHERE 1=1" + where
            + " ORDER BY ts", args).fetchall()
    finally:
        conn.close()

    md = [f"Source: `{path.name}`, telemetry rows: {len(tel)}, alarm rows: {len(alm)}. "
          f"Window: {ctx.window_text}. Telemetry is 1 row per vehicle per second; PDR is stored in %."]
    images = []

    # PDR and RSSI vs distance (neighbour rows only: distance is NULL for the own vehicle)
    dist_rows = [r for r in tel if r[2] is not None]
    xs = [r[2] for r in dist_rows]
    pdr_pts = [(r[2], r[4]) for r in dist_rows if r[4] is not None]
    rssi_pts = [(r[2], r[3]) for r in dist_rows if r[3] is not None]
    md.append(f"### PDR vs distance\n{len(pdr_pts)} samples with distance and PDR.")
    if pdr_pts:
        px, py = zip(*pdr_pts)
        bs = bin_stats(px, py, ctx.bin_m)
        fig, ax = new_fig()
        ax.scatter(px, py, s=8, color=BLUE, alpha=0.25, label="1 Hz sample")
        ax.plot([(b[0] + b[1]) / 2 for b in bs], [b[3] for b in bs], color=ORANGE, linewidth=1.8,
                marker="o", markersize=4, label=f"binned mean ({ctx.bin_m} m)")
        ax.axhline(90, color=GRAY, linestyle="--", linewidth=1, label="A2 / A4 target 90 %")
        ax.set_xlabel("distance (m)")
        ax.set_ylabel("PDR (%)")
        ax.set_ylim(0, 105)
        ax.set_title(ptitle("PDR vs distance"))
        ax.legend(frameon=False, fontsize=8, loc="lower left")
        images.append(save(fig, ctx.out, "pdr_vs_distance.png"))
        md.append(img(images[-1], "PDR vs distance"))
        ok = [b for b in bs if b[3] >= 90]
        best = max(ok, key=lambda b: b[0]) if ok else None
        md.append("Highest distance bin with mean PDR >= 90 %: " +
                  (f"{best[0]:.0f}-{best[1]:.0f} m (mean {best[3]:.1f} %)." if best else "none."))
        md.append(md_table(["distance bin (m)", "n", "mean PDR %", "min %", "max %"],
                           [(f"{b[0]:.0f}-{b[1]:.0f}", b[2], f"{b[3]:.1f}", f"{b[4]:.1f}", f"{b[5]:.1f}")
                            for b in bs]))

    md.append("### RSSI vs distance")
    if rssi_pts:
        rx, ry = zip(*rssi_pts)
        bs = bin_stats(rx, ry, ctx.bin_m)
        fig, ax = new_fig()
        ax.scatter(rx, ry, s=8, color=BLUE, alpha=0.25, label="1 Hz sample")
        ax.plot([(b[0] + b[1]) / 2 for b in bs], [b[3] for b in bs], color=ORANGE, linewidth=1.8,
                marker="o", markersize=4, label=f"binned mean ({ctx.bin_m} m)")
        ax.set_xlabel("distance (m)")
        ax.set_ylabel("RSSI (dBm)")
        ax.set_title(ptitle("RSSI vs distance"))
        ax.legend(frameon=False, fontsize=8, loc="lower left")
        images.append(save(fig, ctx.out, "rssi_vs_distance.png"))
        md.append(img(images[-1], "RSSI vs distance"))
        md.append(md_table(["distance bin (m)", "n", "mean RSSI dBm", "min", "max"],
                           [(f"{b[0]:.0f}-{b[1]:.0f}", b[2], f"{b[3]:.1f}", f"{b[4]:.0f}", f"{b[5]:.0f}")
                            for b in bs]))
    else:
        md.append("No RSSI samples.")

    # TTC at warning transitions: 0->1 = Caution, into 2 from 0/1 = Critical (per vehicle)
    trans = []
    no_ttc = 0
    prev = {}
    for ts, vid, _dist, _rssi, _pdr, ttc, warn in tel:
        p = prev.get(vid)
        prev[vid] = warn
        if warn is None or p is None:
            continue
        kind = None
        if p == 0 and warn == 1:
            kind = "Caution"
        elif warn == 2 and p in (0, 1):
            kind = "Critical"
        if kind is None:
            continue
        if ttc is None:
            no_ttc += 1
        else:
            trans.append((ts, vid, kind, ttc))
    md.append("### TTC at warning moments")
    if trans:
        rows = []
        for kind, target in (("Caution", 4.0), ("Critical", 2.0)):
            vals = [t[3] for t in trans if t[2] == kind]
            if not vals:
                rows.append((kind, 0, "-", "-", "-", "-", "-"))
                continue
            inside = sum(1 for v in vals if abs(v - target) <= 0.5)
            rows.append((kind, len(vals), f"{sum(vals) / len(vals):.2f}", f"{min(vals):.1f}",
                         f"{max(vals):.1f}", f"{inside}/{len(vals)}", f"{target:.1f} +/- 0.5 s"))
        md.append(md_table(["warning", "n", "mean TTC s", "min s", "max s", "inside target +/-0.5 s",
                            "A6 target"], rows))
        fig, axes = new_fig(1, 2, w=8, h=3.6)
        for ax, kind, target, color in ((axes[0], "Caution", 4.0, ORANGE),
                                        (axes[1], "Critical", 2.0, RED)):
            vals = [t[3] for t in trans if t[2] == kind]
            ax.hist(vals, bins=[x * 0.25 for x in range(0, 41)], color=color, alpha=0.85)
            ax.axvspan(target - 0.5, target + 0.5, color=GRAY, alpha=0.15, label="target +/- 0.5 s")
            ax.axvline(target, color=GRAY, linestyle="--", linewidth=1)
            ax.set_title(ptitle(f"TTC at {kind} (n={len(vals)})"), fontsize=10)
            ax.set_xlabel("TTC (s)")
            ax.set_ylabel("count")
            ax.legend(frameon=False, fontsize=8)
        images.append(save(fig, ctx.out, "ttc_at_warning.png"))
        md.append(img(images[-1], "TTC at warning"))
        md.append("Each row: vehicle, time, transition, TTC: first 30 shown.")
        md.append(md_table(["time", "vehicle", "transition", "TTC s"],
                           [(local_time(t[0]), t[1], t[2], f"{t[3]:.1f}") for t in trans[:30]]))
    else:
        md.append("No warning transitions with a TTC value in this window.")
    if no_ttc:
        md.append(f"{no_ttc} warning transition(s) had no TTC value (NULL) and are not counted.")

    # Alarms
    md.append("### Alarms")
    if alm:
        counts = Counter((a[2], a[3]) for a in alm)
        items = sorted(counts.items(), key=lambda kv: -kv[1])
        fig, ax = new_fig(w=7.5, h=max(2.5, 0.4 * len(items) + 1))
        labels = [f"{t} ({s})" for (t, s), _ in items]
        ax.barh(range(len(items)), [c for _, c in items], color=BLUE)
        ax.set_yticks(range(len(items)))
        ax.set_yticklabels(labels, fontsize=8)
        ax.invert_yaxis()
        ax.set_xlabel("count")
        ax.set_title(ptitle("Alarm counts by type"))
        for i, (_, c) in enumerate(items):
            ax.text(c, i, f" {c}", va="center", fontsize=8)
        images.append(save(fig, ctx.out, "alarm_counts.png"))
        md.append(img(images[-1], "Alarm counts"))
        md.append(md_table(["type", "severity", "count"],
                           [(t, s, c) for (t, s), c in items]))
    else:
        md.append("No alarms in this window.")

    md.append("### False-alarm summary")
    md.append("The database cannot tell a false alarm from a real one. Review each row by hand "
              "(list below) and record the verdict in docs/test_plan.md.")
    crash = [a for a in alm if a[2] in ("Crash / SOS", "Rollover")]
    md.append(f"- Crash / SOS and Rollover alarms: **{len(crash)}** "
              "(A12 pass = 0 in normal use; each one needs a manual check).")
    for kind in ("Collision risk", "Hard braking", "Road hazard"):
        n = sum(1 for a in alm if a[2] == kind)
        md.append(f"- {kind}: {n} (count as false alarms after review).")
    if crash or any(a[2] == "Collision risk" for a in alm):
        rows = [(local_time(a[0]), a[1], a[2], a[3]) for a in alm
                if a[2] in ("Crash / SOS", "Rollover", "Collision risk", "Hard braking", "Road hazard")]
        md.append(md_table(["time", "vehicle", "type", "severity"], rows[:60]))
        if len(rows) > 60:
            md.append(f"({len(rows) - 60} more rows not shown.)")
    return ("db", "\n\n".join(md), images)


# ---------------------------------------------------------------- --rtt (A3 latency)

def load_rtt(path):
    lines = Path(path).read_text(encoding="utf-8", errors="replace").splitlines()
    for i, line in enumerate(lines):
        cells = [c.strip() for c in line.split(",")]
        if "rtt_ms" in cells:
            idx = cells.index("rtt_ms")
            vals = []
            for row in lines[i + 1:]:
                parts = [c.strip() for c in row.split(",")]
                if len(parts) > idx:
                    try:
                        vals.append(float(parts[idx]))
                    except ValueError:
                        pass
            return vals, "CSV (ts,rtt_ms)"
    vals = []
    for line in lines:
        for rx in PROBE_RES:
            m = rx.search(line)
            if m:
                vals.append(float(m.group(1)))
                break
    return vals, "modbus_probe text (LAST_RTT_MS / rtt=)"


def analyze_rtt(ctx):
    vals, kind = load_rtt(ctx.path)
    if not vals:
        raise ValueError("no RTT samples found")
    one_way = [v / 2.0 for v in vals]
    mean = sum(one_way) / len(one_way)
    mx = max(one_way)
    s = sorted(one_way)
    p95 = s[min(len(s) - 1, int(0.95 * len(s)))]
    ok = mean < 50 and mx < 100
    fig, ax = new_fig()
    ax.hist(one_way, bins=20, color=BLUE, alpha=0.85)
    ax.axvline(mean, color=ORANGE, linewidth=1.8, label=f"mean {mean:.1f} ms")
    ax.axvline(50, color=GRAY, linestyle="--", linewidth=1, label="A3 avg target 50 ms")
    ax.axvline(100, color=RED, linestyle="--", linewidth=1, label="A3 max target 100 ms")
    ax.set_xlabel("one-way latency RTT/2 (ms)")
    ax.set_ylabel("count")
    ax.set_title(ptitle(f"Latency histogram (n={len(vals)})"))
    ax.legend(frameon=False, fontsize=8)
    name = save(fig, ctx.out, f"latency_{Path(ctx.path).stem}.png")
    md = [
        f"Source: `{Path(ctx.path).name}`, format: {kind}. One-way = RTT/2.",
        md_table(["samples", "mean ms", "p95 ms", "max ms", "min ms", "A3 (mean<50, max<100)"],
                 [(len(vals), f"{mean:.1f}", f"{p95:.1f}", f"{mx:.1f}", f"{min(one_way):.1f}",
                   "PASS" if ok else "FAIL")]),
        img(name, "latency histogram"),
    ]
    if "CSV" not in kind:
        md.append("Note: modbus_probe lines are snapshots of the gateway's last-RTT register, so repeated "
                  "values are possible and each sample is not necessarily a separate PING.")
    return ("rtt-" + Path(ctx.path).stem, "\n\n".join(md), [name])


# ---------------------------------------------------------------- --distance-error (A5)

def analyze_distance(ctx):
    rows = []
    with open(ctx.path, newline="", encoding="utf-8-sig") as f:
        lines = [ln for ln in f if ln.strip() and not ln.lstrip().startswith("#")]
    for r in csv.DictReader(lines):
        tape = float(r["tape_m"])
        gps = float(r["gps_m"])
        rows.append((tape, gps))
    if not rows:
        raise ValueError("no rows")
    err = [g - t for t, g in rows]
    table = [(f"{t:.1f}", f"{g:.1f}", f"{e:+.1f}", f"{abs(e):.1f}", "PASS" if abs(e) <= 5 else "FAIL")
             for (t, g), e in zip(rows, err)]
    fig, ax = new_fig(w=8, h=3.8)
    labels = [f"{t:.0f} m" for t, _ in rows]
    colors = [BLUE if abs(e) <= 5 else RED for e in err]
    ax.bar(range(len(rows)), err, color=colors)
    ax.axhline(5, color=GRAY, linestyle="--", linewidth=1, label="+/- 5 m (A5)")
    ax.axhline(-5, color=GRAY, linestyle="--", linewidth=1)
    ax.axhline(0, color="#999999", linewidth=0.8)
    ax.set_xticks(range(len(rows)))
    ax.set_xticklabels(labels, fontsize=8)
    ax.set_ylabel("GPS minus tape (m)")
    ax.set_title(ptitle("GPS distance error"))
    ax.legend(frameon=False, fontsize=8)
    name = save(fig, ctx.out, "distance_error.png")
    tapes = sorted({t for t, _ in rows})
    missing = [d for d in (10, 25, 50, 100) if d not in tapes]
    md = [
        f"Source: `{Path(ctx.path).name}`. Error = GPS - tape. Criterion: |error| <= 5 m.",
        md_table(["tape (m)", "GPS avg (m)", "error (m)", "|error| (m)", "A5"], table),
        f"Max |error|: **{max(abs(e) for e in err):.1f} m**, mean error {sum(err) / len(err):+.2f} m. "
        f"Overall: **{'PASS' if all(abs(e) <= 5 for e in err) else 'FAIL'}**.",
        ("A5 distances not yet in the file: " + ", ".join(f"{d} m" for d in missing) + ".")
        if missing else "All A5 distances (10/25/50/100 m) are present.",
        img(name, "distance error"),
    ]
    return ("distance-" + Path(ctx.path).stem, "\n\n".join(md), [name])


# ---------------------------------------------------------------- --imu-log (S13.3 thresholds, TTC log)

def load_imu(path):
    text = Path(path).read_text(encoding="utf-8", errors="replace").splitlines()
    names = None
    data = []
    skipped = 0
    for raw in text:
        line = TS_PREFIX_RE.sub("", raw.strip()).strip()
        if line.startswith("ms,"):
            names = line.split(",")
            continue
        if names is None:
            skipped += 1
            continue
        parts = line.split(",")
        if len(parts) != len(names):
            skipped += 1
            continue
        try:
            data.append([int(p) for p in parts])
        except ValueError:
            skipped += 1
    if names is None:
        raise ValueError("no CSV header line (ms,a_long_x100,...). Was this recorded with a --log build?")
    cols = {}
    for j, name in enumerate(names):
        base = name[:-5] if name.endswith("_x100") else name
        scale = 100.0 if name.endswith("_x100") else 1.0
        cols[base] = [row[j] for row in data]
        if base == "ttc":
            cols[base] = [None if v == -1 else v / scale for v in cols[base]]
        else:
            cols[base] = [v / scale for v in cols[base]]
    for need in ("ms", "a_long", "a_total", "az_hp", "roll", "pitch", "level", "ttc"):
        if need not in cols:
            raise ValueError(f"column {need} missing from header")
    return cols, len(data), skipped


def analyze_imu(ctx):
    cols, n, skipped = load_imu(ctx.path)
    if n < 2:
        raise ValueError("no data rows")
    t = [(ms - cols["ms"][0]) / 1000.0 for ms in cols["ms"]]
    duration = t[-1]
    resets = sum(1 for a, b in zip(cols["ms"], cols["ms"][1:]) if b < a)
    thr = thresholds()
    md = [
        f"Source: `{Path(ctx.path).name}`: {n} data rows over {duration / 60:.1f} min "
        f"({skipped} non-data lines skipped). Thresholds read from `firmware/v2v_obu/config.h`.",
    ]
    if resets:
        md.append(f"**Warning:** the millis() counter went backwards {resets} time(s): the board rebooted "
                  "during the run. Split the file at the reboot before judging.")
    if duration < 600:
        md.append(f"**Note:** the log is {duration / 60:.1f} min. S13.3 asks for 10 min of normal use.")

    series = OrderedDict([
        ("a_long", ("a_long", "m/s^2", BLUE, "EEBL / braking")),
        ("a_total", ("a_total", "g", ORANGE, "crash")),
        ("az_hp", ("az_hp", "m/s^2", AQUA, "pothole")),
    ])
    fig, axes = new_fig(3, 1, w=8, h=8.2)
    rows = []
    for ax, key in zip(axes, series):
        col, unit, color, label = series[key][0], series[key][1], series[key][2], series[key][3]
        vals = cols[col]
        limit = thr[key]
        ax.plot(t, vals, color=color, linewidth=0.6, label=col)
        for y, style, lab in ((limit, RED, "threshold"), (0.6 * limit, GRAY, "60 %")):
            ax.axhline(y, color=style, linestyle="-" if style == RED else "--", linewidth=1,
                       label=f"{lab} {y:.2f} {unit}")
            ax.axhline(-y, color=style, linestyle="-" if style == RED else "--", linewidth=1)
        ax.set_ylabel(f"{col} ({unit})")
        ax.set_title(ptitle(f"{col}: {label}"), fontsize=10, loc="left")
        ax.legend(frameon=False, fontsize=7, loc="upper right")
        peak = max(abs(v) for v in vals)
        rows.append(_verdict_row(col, unit, peak, limit))
    axes[-1].set_xlabel("time (s)")
    name_t = save(fig, ctx.out, f"imu_thresholds_{Path(ctx.path).stem}.png")

    # roll / pitch against the rollover limit
    peak_rp = max(max(abs(v) for v in cols["roll"]), max(abs(v) for v in cols["pitch"]))
    rows.append(_verdict_row("roll/pitch", "deg", peak_rp, thr["roll"]))

    md.append(md_table(["channel", "max |value|", "threshold", "60 % line", "% of threshold", "S13.3 verdict"],
                       rows))
    md.append("S13.3 rule: keep the default if the normal-use maximum stays below 60 % of each threshold. "
              "Above that, a threshold may be raised, but only with this evidence and your approval.")
    md.append(img(name_t, "IMU threshold plot"))

    # TTC at level transitions in the log
    trans = []
    prev_level = None
    for i, lvl in enumerate(cols["level"]):
        if prev_level is not None and lvl != prev_level and ((prev_level == 0 and lvl == 1) or
                                                              (lvl == 2 and prev_level in (0, 1))):
            trans.append((t[i], "Caution" if lvl == 1 else "Critical", cols["ttc"][i]))
        prev_level = lvl
    md.append("### TTC at FCW transitions in this log")
    if trans:
        md.append(md_table(["t (s)", "transition", "TTC (s)"],
                           [(f"{tt:.2f}", k, "none (inf)" if v is None else f"{v:.2f}") for tt, k, v in trans]))
    else:
        md.append("No level transitions in this log (expected for normal driving).")
    return ("imu-" + Path(ctx.path).stem, "\n\n".join(md), [name_t])


def _verdict_row(name, unit, peak, limit):
    pct = 100.0 * peak / limit if limit else float("nan")
    if peak < 0.6 * limit:
        verdict = "below 60 %: keep default"
    elif peak < limit:
        verdict = "above 60 %: raise only with evidence"
    else:
        verdict = "at or above threshold: check the event before any change"
    return (name, f"{peak:.2f} {unit}", f"{limit:.2f} {unit}", f"{0.6 * limit:.2f} {unit}",
            f"{pct:.0f} %", verdict)


# ---------------------------------------------------------------- summary.md

def write_summary(out_dir, sections, synthetic):
    path = out_dir / "summary.md"
    existing = OrderedDict()
    if path.exists():
        old = path.read_text(encoding="utf-8")
        was_synthetic = "SYNTHETIC - NOT REAL" in old[:600]
        if was_synthetic == synthetic:
            for m in SECTION_RE.finditer(old):
                existing[m.group(1)] = m.group(2)
        else:
            print(f"note: {path} had {'synthetic' if was_synthetic else 'real'} results; rebuilt as "
                  f"{'synthetic' if synthetic else 'real'}.")
    for sid, body in sections:
        existing[sid] = body
    parts = ["# V2V field-test results summary", ""]
    if synthetic:
        parts += [SYN_BANNER, ""]
    parts += [f"Generated by `tools/log_analyzer.py` on {dt.datetime.now():%Y-%m-%d %H:%M}. "
              "Sections are replaced by id on each run; images are in this folder.", ""]
    for sid, body in existing.items():
        parts += [f"<!-- section:{sid} -->", body.strip(), f"<!-- /section:{sid} -->", ""]
    path.write_text("\n".join(parts), encoding="utf-8")
    return path


# ---------------------------------------------------------------- main

def main(argv=None):
    global TITLE_PREFIX
    ap = argparse.ArgumentParser(description="Analyse V2V field-test data (PNG + docs/results/summary.md)")
    ap.add_argument("--db", help="SCADA historian SQLite file")
    ap.add_argument("--rtt", help="A3 latency: CSV (ts,rtt_ms) or modbus_probe text")
    ap.add_argument("--distance-error", help="A5 CSV (tape_m,gps_m)")
    ap.add_argument("--imu-log", help="LOG_MODE CSV from serial_log.py")
    ap.add_argument("--out-dir", default=str(DEFAULT_OUT))
    ap.add_argument("--from", dest="time_from", help="window start for --db (epoch ms or local ISO time)")
    ap.add_argument("--to", dest="time_to", help="window end for --db")
    ap.add_argument("--bin-m", type=float, default=25.0, help="distance bin width (m)")
    ap.add_argument("--synthetic", action="store_true", help="force the SYNTHETIC banner")
    args = ap.parse_args(argv)

    given = [(f, p) for f, p in (("--db", args.db), ("--rtt", args.rtt),
                                 ("--distance-error", args.distance_error), ("--imu-log", args.imu_log)) if p]
    if not given:
        ap.error("give at least one of --db, --rtt, --distance-error, --imu-log")

    synthetic = args.synthetic or any(Path(p).name.startswith("sample_") for _, p in given)
    TITLE_PREFIX = "[SYNTHETIC] " if synthetic else ""
    out = Path(args.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    t0 = parse_time(args.time_from)
    t1 = parse_time(args.time_to)
    window_text = "all rows" if t0 is None and t1 is None else (
        f"{local_time(t0) if t0 else 'start'} to {local_time(t1) if t1 else 'end'}")

    analysers = {"--db": analyze_db, "--rtt": analyze_rtt,
                 "--distance-error": analyze_distance, "--imu-log": analyze_imu}
    sections, status, failed = [], [], False
    for flag, _ in (("--db", args.db), ("--rtt", args.rtt),
                    ("--distance-error", args.distance_error), ("--imu-log", args.imu_log)):
        p = dict(given).get(flag)
        if p is None:
            status.append(f"- `{flag}`: not provided")
            continue
        if not Path(p).exists():
            status.append(f"- `{flag}`: **MISSING** (`{p}` not found)")
            failed = True
            continue
        ctx = argparse.Namespace(path=p, out=out, t0=t0, t1=t1, bin_m=args.bin_m, window_text=window_text)
        try:
            sid, body, images = analysers[flag](ctx)
        except Exception as e:  # noqa: BLE001 - report the failure in the summary and keep going
            status.append(f"- `{flag}`: **FAILED** ({e})")
            failed = True
            continue
        sections.append((sid, f"## {flag} {Path(p).name}\n\n{body}"))
        status.append(f"- `{flag}`: `{Path(p).name}` analysed, images: " +
                      (", ".join(images) if images else "none"))
        print(f"{flag}: {Path(p).name} -> {', '.join(images)}")

    try:
        thr = thresholds()
        thr_text = ", ".join(f"{k} {v:.2f}" for k, v in thr.items())
    except (OSError, KeyError) as e:
        thr_text = f"could not read config.h ({e})"
        failed = True
    status_block = "## Inputs of the latest run\n\n" + "\n".join(status) + \
        f"\n\nThresholds from config.h: {thr_text}."
    sections.insert(0, ("inputs", status_block))

    path = write_summary(out, sections, synthetic)
    print(f"summary: {path}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
