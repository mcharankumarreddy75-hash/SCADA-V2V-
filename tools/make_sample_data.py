#!/usr/bin/env python3
"""Generate SYNTHETIC sample inputs for tools/log_analyzer.py.

Every number here is made up with a fixed random seed. These are NOT real measurements and must
never be quoted in the report. All files are named sample_* and the analyzer marks their output
SYNTHETIC.

Usage (repo root):
    tools/.venv/Scripts/python.exe tools/make_sample_data.py            # writes data/sample/
    tools/.venv/Scripts/python.exe tools/make_sample_data.py --out DIR

Files written:
    sample_v2v.db                 SQLite historian, schema from scada/historian/schema.sql
    sample_rtt.csv                A3 input: header ts,rtt_ms
    sample_probe_rtt.txt          A3 alternative: modbus_probe-style lines with LAST_RTT_MS
    sample_distance_tape.csv      A5 input: header tape_m,gps_m
    sample_imu_normal_drive.csv   S13.3 input: LOG_MODE CSV, 5 min of normal driving, serial_log prefixes
    sample_imu_fcw_run.csv        LOG_MODE CSV with an approach (Caution then Critical), 60 s
"""
import argparse
import math
import random
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "scada" / "historian" / "schema.sql"
DEFAULT_OUT = ROOT / "data" / "sample"
BANNER = "# SYNTHETIC - NOT REAL MEASUREMENTS (generated by tools/make_sample_data.py)"
T0_MS = 1_795_000_000_000          # arbitrary epoch start, synthetic
IMU_HEADER = "ms,a_long_x100,a_total_x100,az_hp_x100,roll_x100,pitch_x100,speed_x100,level,ttc_x100"
GRAVITY = 9.81


def write_historian(path, rng):
    if path.exists():
        path.unlink()
    conn = sqlite3.connect(path)
    try:
        conn.executescript(SCHEMA.read_text(encoding="utf-8"))
        tel, alarms = [], []
        duration_s = 30 * 60
        episodes = [t for t in range(200, duration_s, 420)]   # an approach every 7 min
        in_episode = {}
        for start in episodes:
            for k in range(26):                               # 25 s approach, 1 row/s
                in_episode[start + k] = k
        alarm_open = {}
        for s in range(duration_s):
            ts = T0_MS + s * 1000
            # vehicle 2 is the neighbour; it drives a cycle that brings it 20..240 m from vehicle 1
            dist = 130 + 110 * math.sin(s / 540.0) + rng.gauss(0, 2)
            ttc = None
            if s in in_episode:
                k = in_episode[s]
                ttc = 8.0 - k * (7.5 / 25.0) + rng.gauss(0, 0.05)     # 8 s -> 0.5 s
                dist = max(ttc, 0.0) * 8.0                            # closing at 8 m/s
            else:
                dist = max(dist, 20.0)
            pdr = 100.0 - max(0.0, dist - 220.0) * 0.9 + rng.gauss(0, 1.5)
            if rng.random() < 0.01:
                pdr -= 15.0                                           # occasional drop
            pdr = min(100.0, max(0.0, pdr))
            rssi = round(-35 - 22 * math.log10(max(dist, 1.0)) + rng.gauss(0, 2.5))
            warn = 0
            if ttc is not None:
                warn = 2 if ttc < 2.0 else (1 if ttc < 4.0 else 0)
            lat = 0.0 + 0.00001 * s
            lon = 0.0
            # own vehicle row (distance/rssi/pdr/ttc NULL for own)
            tel.append((ts, 1, lat, lon, 12.0 + rng.gauss(0, 1), 90.0, rng.gauss(0, 0.3),
                        round(rng.gauss(0, 1)), round(rng.gauss(0, 1.5)), 0, 88, None, None,
                        None, None, 0))
            tel.append((ts, 2, lat + 0.0002, lon + 0.0003, 12.0 + rng.gauss(0, 1), 270.0,
                        rng.gauss(0, 0.3), round(rng.gauss(0, 1)), round(rng.gauss(0, 1.5)), 0, 84,
                        rssi, round(pdr, 1), round(dist, 1), None if ttc is None else round(ttc, 2),
                        warn))
        # alarms: a Collision risk per warn=2 rising edge, a Hard braking and a hazard, one link loss
        prev_w = 0
        for r in tel:
            if r[1] != 2:
                continue
            w, ts = r[15], r[0]
            if w == 2 and prev_w != 2:
                alarms.append((ts, 2, "Collision risk", "HIGH", 0.0, 0.0, 0, None, ts + 4000))
            prev_w = w
        alarms.append((T0_MS + 611_000, 2, "Hard braking", "MEDIUM", 0.0, 0.0, 1, T0_MS + 612_000, T0_MS + 614_000))
        alarms.append((T0_MS + 1_203_000, 2, "Road hazard", "MEDIUM", 0.0, 0.0, 0, None, T0_MS + 1_204_500))
        alarms.append((T0_MS + 1_510_000, 2, "V2V link lost", "MEDIUM", 0.0, 0.0, 1, T0_MS + 1_511_000,
                       T0_MS + 1_513_000))
        conn.executemany("INSERT INTO telemetry (ts, vehicle_id, lat, lon, speed_kmh, heading, accel, roll, "
                         "pitch, flags, battery, rssi, pdr, distance, ttc, warn) "
                         "VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)", tel)
        conn.executemany("INSERT INTO alarms (ts, vehicle_id, type, severity, lat, lon, acked, ack_ts, "
                         "cleared_ts) VALUES (?,?,?,?,?,?,?,?,?)", alarms)
        conn.commit()
    finally:
        conn.close()
    return len(tel), len(alarms)


def write_rtt(path, rng):
    lines = ["ts,rtt_ms"]
    t = T0_MS
    for i in range(100):
        rtt = 22 + abs(rng.gauss(0, 7))
        if i in (37, 81):
            rtt = 88 + rng.random() * 6           # two slow pings, still under 100 ms one-way
        lines.append(f"{t + i * 1000},{rtt:.1f}")
    path.write_text(BANNER + "\n" + "\n".join(lines) + "\n", encoding="utf-8")


def write_probe_rtt(path, rng):
    out = [BANNER]
    for i in range(100):
        rtt = 22 + abs(rng.gauss(0, 7))
        out.append(f"12:{i // 60:02d}:{i % 60:02d} readback: reg103(trigger)=1 "
                   f"reg4(CMD_ACK_COUNT)={i + 1} reg3(LAST_RTT_MS)={round(rtt)}")
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def write_distance(path, rng):
    lines = [BANNER, "tape_m,gps_m"]
    for rep in range(3):
        for tape in (10.0, 25.0, 50.0, 100.0):
            gps = tape + 1.2 + rng.gauss(0, 1.5)
            lines.append(f"{tape:.1f},{gps:.1f}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _csv_line(ms, a_long, a_total, az_hp, roll, pitch, speed, level, ttc):
    def x(v):
        return int(round(v * 100))
    ttc_x = -1 if ttc is None else x(ttc)
    return f"{ms},{x(a_long)},{x(a_total)},{x(az_hp)},{x(roll)},{x(pitch)},{x(speed)},{level},{ttc_x}"


def write_imu_normal(path, rng):
    lines = [BANNER, "reading COM7 @ 115200 (synthetic)", IMU_HEADER]
    n = 5 * 60 * 20                                   # 5 min at 20 Hz
    a_long_state = 0.0
    for i in range(n):
        ms = 100_000 + i * 50
        t = i / 20.0
        speed = 6 + 4 * math.sin(t / 30.0)
        # gentle speed changes only; the largest is a -1.6 m/s^2 slow-down
        a_long_state += 0.2 * ((rng.gauss(0, 0.35) + (-1.6 if 200 < t < 203 else 0.0)) - a_long_state)
        a_long = a_long_state
        az_hp = rng.gauss(0, 0.6)
        if 120.0 <= t < 120.1:
            az_hp = -9.5                               # one pothole, below the 14.7 m/s^2 threshold
        ax, ay, az = a_long, rng.gauss(0, 0.3), GRAVITY + az_hp
        a_total = math.sqrt(ax * ax + ay * ay + az * az) / GRAVITY
        roll = rng.gauss(0, 1.0)
        pitch = rng.gauss(0, 1.5)
        line = _csv_line(ms, a_long, a_total, az_hp, roll, pitch, speed, 0, None)
        lines.append(f"12:00:{t % 60:06.3f} {line}")  # serial_log-style prefix
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_imu_fcw(path, rng):
    lines = [BANNER, IMU_HEADER]
    n = 60 * 20
    for i in range(n):
        ms = 200_000 + i * 50
        t = i / 20.0
        ttc = None
        if 10.0 <= t < 30.0:
            ttc = 9.0 - (t - 10.0) * (8.5 / 20.0)    # 9 s -> 0.5 s, then the vehicle stops
            if ttc <= 0.0:
                ttc = None
        level = 0 if ttc is None else (2 if ttc <= 2.0 else (1 if ttc <= 4.0 else 0))
        a_long = rng.gauss(0, 0.2)
        line = _csv_line(ms, a_long, 1.0 + abs(rng.gauss(0, 0.01)), rng.gauss(0, 0.5),
                         rng.gauss(0, 0.8), rng.gauss(0, 1.0), 8.0 + rng.gauss(0, 0.1), level, ttc)
        lines.append(line)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def generate(out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20261125)
    rows, alarms = write_historian(out_dir / "sample_v2v.db", rng)
    write_rtt(out_dir / "sample_rtt.csv", rng)
    write_probe_rtt(out_dir / "sample_probe_rtt.txt", rng)
    write_distance(out_dir / "sample_distance_tape.csv", rng)
    write_imu_normal(out_dir / "sample_imu_normal_drive.csv", rng)
    write_imu_fcw(out_dir / "sample_imu_fcw_run.csv", rng)
    return {"telemetry_rows": rows, "alarm_rows": alarms}


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate SYNTHETIC sample data (not real measurements)")
    ap.add_argument("--out", default=str(DEFAULT_OUT), help="output folder (default data/sample)")
    args = ap.parse_args(argv)
    info = generate(args.out)
    print(f"SYNTHETIC samples written to {args.out}: {info}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
